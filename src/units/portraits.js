// (public/portraits/<sheet>.png 96x96 and <sheet>@48.png 48x48, transparent background -- the UI draws the frame).
// Portraits are keyed by SPRITE SHEET; a class key (or a unit) resolves to its sheet through the roster, so a class
// that borrows another sheet (guardian -> knight, zombie -> skeleton, heroes with spriteOf) gets that sheet's face.
//
//   portraitUrl('03_knight_paladin')      -> '/portraits/03_knight_paladin.png'
//   portraitUrl('wyrmlancer', 48)            -> '/portraits/34_dragoon_wyrmslayer@48.png'
//   portraitUrl(unit)                     -> uses unit.spriteName, else unit.cls
//   portraitUrl('nope')                   -> null   (caller falls back to its own crop / letter placeholder)
//
// Portraits face the same way as the unit's front idle on the field (pack_sprites rowFlip[0] is applied at pack time),
// so an enemy card that mirrors its unit can mirror the portrait with `transform: scaleX(-1)` exactly as before.
