const BASE = (() => { try { return import.meta.env?.BASE_URL || '/'; } catch { return '/'; } })();

/** Sheet name for a sheet / class key / unit-like object, or null. */
export function portraitSheet(x) {
  if (!x) return null;
  if (typeof x === 'object') return portraitSheet(x.spriteName || x.sprite) || portraitSheet(x.cls);
  if (SHEETS.has(x)) return x;
  const s = CLASSES[x]?.sprite || ROSTER[x]?.sprite;   // CLASSES covers heroes with spriteOf
  return s && SHEETS.has(s) ? s : null;
}

/** URL of the packed portrait (size 96 or 48; anything <= 48 picks the 48) or null when there is none. */
export function portraitUrl(sheetOrClass, size = 96) {
  const s = portraitSheet(sheetOrClass);
  if (!s) return null;
  return `${BASE}portraits/${encodeURIComponent(s)}${size <= 48 ? '@48' : ''}.png`;
}

const loaded = new Map();   // url -> Promise<HTMLImageElement|null>
/** Warm the browser cache for a list of sheets / classes / units. Resolves (never rejects) with the URLs that loaded,
 *  or after `timeout` ms with whatever finished by then. Missing portraits are skipped. */
export function preloadPortraits(list, { sizes = [96], timeout = 6000 } = {}) {
  if (typeof Image === 'undefined') return Promise.resolve([]);
  const urls = [...new Set((list || []).flatMap((x) => sizes.map((sz) => portraitUrl(x, sz))).filter(Boolean))];
  const jobs = urls.map((u) => {
    if (!loaded.has(u)) loaded.set(u, new Promise((res) => {
      const img = new Image(); img.decoding = 'async';
      img.onload = () => res(img); img.onerror = () => { loaded.delete(u); res(null); };
      img.src = u;
    }));
    return loaded.get(u).then((img) => (img ? u : null));
  });
  const all = Promise.all(jobs).then((r) => r.filter(Boolean));
  return Promise.race([all, new Promise((r) => setTimeout(() => r(urls.filter((u) => loaded.has(u))), timeout))]);
}
